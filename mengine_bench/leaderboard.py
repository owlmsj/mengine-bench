"""LEADERBOARD.md from `results/**/result.json`, verified bundles only.

Two steps, so ranking can run apart from the code-executing audit:
`verification_report` re-verifies every bundle (verify.py executes workspace
code), and `build_leaderboard_from_report` ranks from result.json plus that
JSON report alone. An edited, failed or unreported bundle drops off the table and is
listed under "Skipped" with the reason instead of silently ranking.
"""

from __future__ import annotations

import hashlib
import json
import os
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path

from mengine_bench import visual
from mengine_bench.bundle import RESULT_NAME, SUMMARY_NAME
from mengine_bench.core import SUITES

# verify.py (and the task catalog behind it) is imported only inside
# verification_report: the publish job must not even load task checks.
# 2: entries carry `partial` (not the exact suite task set, review R04).
REPORT_VERSION = 2

LEADERBOARD_HEADER = """# Leaderboard

Generated by `mengine-bench leaderboard` from `results/**/result.json`; do not
edit by hand. Only bundles that pass `mengine-bench verify` are ranked. One
table per suite, scoring version, judge and visual grading profile
(rendered: browser + vision judge; unrendered: visual tasks not solvable):
scores from different groups are not comparable. Deterministic checks and scores are
re-verified from the saved workspaces; timings and judge votes are
self-reported (docs/SUBMITTING.md). Runs that are not exactly their declared
suite's task set are listed as partial and never ranked.
"""


@dataclass(frozen=True)
class RankedBundle:
    result: dict[str, object]
    summary_link: str


@dataclass(frozen=True)
class Leaderboard:
    markdown: str
    ranked: int
    skipped: list[tuple[str, str]]
    partial: list[str] = field(default_factory=list)


def _fmt(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.1f}"
    return str(value)


def _link(path: Path, base: Path) -> str:
    return Path(os.path.relpath(path.resolve(), base.resolve())).as_posix()


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verification_report(results_dir: Path, link_base: Path) -> dict[str, object]:
    """Verify every bundle; JSON-ready. Executes submission code: read-only jobs only."""
    from mengine_bench.verify import FAIL, verify_bundle

    entries: list[dict[str, object]] = []
    for result_file in sorted(results_dir.rglob(RESULT_NAME)):
        bundle = result_file.parent
        report = verify_bundle(bundle)
        entries.append({"bundle": _link(bundle, link_base), "ok": report.ok, "partial": report.partial,
                        "failed": [item.name for item in report.items if item.status == FAIL],
                        "result_sha256": _sha256(result_file)})
    return {"report_version": REPORT_VERSION, "bundles": entries}


def _report_entries(report: Mapping[str, object]) -> dict[str, Mapping[str, object]]:
    version = report.get("report_version")
    if version != REPORT_VERSION:
        raise ValueError(f"verification report: received report_version {version!r}; expected {REPORT_VERSION}")
    bundles = report.get("bundles")
    shape = "a list of {bundle: str, ok: bool, partial: bool, failed: [str], result_sha256: str}"
    if not isinstance(bundles, list):
        raise ValueError(f"verification report: received bundles {bundles!r:.80}; expected {shape}")
    entries: dict[str, Mapping[str, object]] = {}
    for entry in bundles:
        if not (isinstance(entry, dict) and isinstance(entry.get("bundle"), str)
                and isinstance(entry.get("ok"), bool) and isinstance(entry.get("partial"), bool)
                and isinstance(entry.get("result_sha256"), str)
                and isinstance(entry.get("failed"), list)):
            raise ValueError(f"verification report: received bundle entry {entry!r:.120}; expected {shape}")
        entries[entry["bundle"]] = entry
    return entries


@dataclass
class CollectedBundles:
    ranked: list[RankedBundle] = field(default_factory=list)
    skipped: list[tuple[str, str]] = field(default_factory=list)
    partial: list[str] = field(default_factory=list)


def collect_from_report(results_dir: Path, link_base: Path, report: Mapping[str, object]) -> CollectedBundles:
    entries = _report_entries(report)
    found = CollectedBundles()
    ranked, skipped = found.ranked, found.skipped
    for result_file in sorted(results_dir.rglob(RESULT_NAME)):
        bundle = result_file.parent
        name = _link(bundle, link_base)
        entry = entries.get(name)
        if entry is None:
            skipped.append((name, "not in the verification report"))
            continue
        if not entry["ok"]:
            failed = entry["failed"]
            assert isinstance(failed, list)
            skipped.append((name, "verify failed: " + ", ".join(str(item) for item in failed)))
            continue
        # Binds the report to the exact bytes ranked, so a later edit cannot ride on an old PASS.
        if entry["result_sha256"] != _sha256(result_file):
            skipped.append((name, "result.json changed since verification"))
            continue
        if entry["partial"]:
            found.partial.append(name)
            continue
        result = json.loads(result_file.read_text(encoding="utf-8"))
        ranked.append(RankedBundle(result=result, summary_link=_link(bundle / SUMMARY_NAME, link_base)))
    return found


def visual_profile_of(result: dict[str, object]) -> str:
    """Recorded grading profile; bundles from before it existed are derived
    from their task flags (review R10), so a no-browser run never ranks with
    rendered ones."""
    grading = result.get("grading")
    if isinstance(grading, dict) and isinstance(grading.get("visual"), str):
        return str(grading["visual"])
    tasks = result.get("tasks")
    flags = [task.get("flags") or [] for task in tasks if isinstance(task, dict)] if isinstance(tasks, list) else []
    degraded = any(flag in (visual.NO_BROWSER, visual.NO_JUDGE, visual.PROFILE_UNRENDERED)
                   for task_flags in flags for flag in task_flags)
    return visual.PROFILE_UNRENDERED if degraded else visual.PROFILE_RENDERED


def build_leaderboard(results_dir: Path, link_base: Path) -> Leaderboard:
    """Verify and rank in one process; for local use, never in a job that can push."""
    return build_leaderboard_from_report(results_dir, link_base, verification_report(results_dir, link_base))


def build_leaderboard_from_report(results_dir: Path, link_base: Path, report: Mapping[str, object]) -> Leaderboard:
    """Pure JSON: reads result.json and the report; imports and runs no task check."""
    found = collect_from_report(results_dir, link_base, report)
    ranked, skipped = found.ranked, found.skipped
    groups: dict[tuple[str, str, str, str], list[RankedBundle]] = {}
    for entry in ranked:
        judge = entry.result.get("judge")
        label = str(judge["label"]) if isinstance(judge, dict) else ""
        key = (str(entry.result["suite"]), str(entry.result["scoring_version"]), label,
               visual_profile_of(entry.result))
        groups.setdefault(key, []).append(entry)
    order = {suite: index for index, suite in enumerate(SUITES)}
    sections = [LEADERBOARD_HEADER]
    for key in sorted(groups, key=lambda key: (order.get(key[0], 99), key[1], key[2], key[3])):
        suite, version, label, profile = key
        title = f"judge {label}" if label else "no judge"
        rows = sorted(groups[key], key=lambda e: -float(e.result["totals"]["objective"]))  # type: ignore[index]
        sections.append(f"## {suite.upper()}, {title}, visual {profile} (scoring {version})\n\n" + _table(rows))
    if not groups:
        sections.append("No verified results yet.\n")
    if found.partial:
        lines = [f"- `{name}`: verified, but not exactly its suite's task set" for name in found.partial]
        sections.append("## Partial runs (not ranked)\n\n" + "\n".join(lines) + "\n")
    if skipped:
        lines = [f"- `{name}`: {reason}" for name, reason in skipped]
        sections.append("## Skipped bundles\n\n" + "\n".join(lines) + "\n")
    return Leaderboard(markdown="\n".join(sections), ranked=len(ranked), skipped=skipped,
                       partial=found.partial)


def _table(rows: Iterable[RankedBundle]) -> str:
    lines = ["| # | agent | model | effort | OBJECTIVE | ACCURACY | solved | agent time (s) | SUBJECTIVE | "
             "COMPOSITE | date | bench | bundle | audit |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for rank, entry in enumerate(rows, start=1):
        row = entry.result
        agent, totals = row["agent"], row["totals"]
        assert isinstance(agent, dict) and isinstance(totals, dict)
        lines.append(f"| {rank} | {agent['name']} {agent.get('version') or ''} | {agent['model']} | "
                     f"{_fmt(agent.get('effort'))} | {_fmt(totals['objective'])} | {_fmt(totals.get('accuracy'))} | "
                     f"{totals['solved']}/{totals['total']} | {_fmt(totals.get('total_agent_s'))} | "
                     f"{_fmt(totals.get('subjective'))} | {_fmt(totals.get('composite'))} | {row['date']} | "
                     f"{row['bench_version']} | [summary]({entry.summary_link}) | verified |")
    return "\n".join(lines) + "\n"
