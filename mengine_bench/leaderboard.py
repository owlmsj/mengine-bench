"""LEADERBOARD.md from `results/**/result.json`.

Scores are self-reported: the maintainer reviews each result pull request
before merging it, and the table trusts what was merged. A run that is not
exactly its suite's task set, that recorded preflight findings, that waits
for the judge, or that ran an older bench (other prompts, so other scores) is
listed apart and never ranked.
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

from mengine_bench import __version__, catalog
from mengine_bench.bundle import RESULT_NAME, SUMMARY_NAME
from mengine_bench.core import SUITES

LEADERBOARD_HEADER = """# Leaderboard

Generated by `mengine-bench leaderboard` from `results/**/result.json`; do not
edit by hand. Scores are self-reported by each submitter and reviewed by the
maintainer before merge; the transcripts are in each bundle. One table per
suite, scoring version, judge and visual grading profile (rendered: browser +
vision judge; unrendered: visual tasks not solvable): scores from different
groups are not comparable. Only runs of the current bench version are ranked;
runs of an older bench, runs that are not exactly their suite's task set, that
started with preflight findings (README, "Run hygiene") or that wait for the
judge are listed apart.
"""


@dataclass(frozen=True)
class RankedBundle:
    result: dict[str, object]
    summary_link: str


@dataclass(frozen=True)
class Leaderboard:
    markdown: str
    ranked: int
    # (bundle, why it is not ranked)
    unranked: list[tuple[str, str]] = field(default_factory=list)


def _fmt(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.1f}"
    return str(value)


def _link(path: Path, base: Path) -> str:
    return Path(os.path.relpath(path.resolve(), base.resolve())).as_posix()


def is_complete_suite(result: dict[str, object]) -> bool:
    """True when the run holds every task of its declared suite exactly once."""
    tasks = result["tasks"]
    assert isinstance(tasks, list)
    ids = [str(task["id"]) for task in tasks]
    expected = {task.id for task in catalog.tasks(str(result["suite"]))}
    return len(ids) == len(set(ids)) and set(ids) == expected


def _group_key(result: dict[str, object]) -> tuple[str, str, str, str]:
    judge = result.get("judge")
    label = str(judge["label"]) if isinstance(judge, dict) else ""
    grading = result["grading"]
    assert isinstance(grading, dict)
    return str(result["suite"]), str(result["scoring_version"]), label, str(grading["visual"])


def build_leaderboard(results_dir: Path, link_base: Path) -> Leaderboard:
    groups: dict[tuple[str, str, str, str], list[RankedBundle]] = {}
    unranked: list[tuple[str, str]] = []
    for result_file in sorted(results_dir.rglob(RESULT_NAME)):
        bundle = result_file.parent
        result = json.loads(result_file.read_text(encoding="utf-8"))
        if result.get("bench_version") != __version__:
            reason = f"bench {result.get('bench_version')}; only bench {__version__} runs are ranked"
            unranked.append((_link(bundle, link_base), reason))
            continue
        if not is_complete_suite(result):
            unranked.append((_link(bundle, link_base), "not exactly its suite's task set"))
            continue
        if result.get("preflight"):
            unranked.append((_link(bundle, link_base), "started with preflight findings"))
            continue
        if result.get("judge_pending"):
            unranked.append((_link(bundle, link_base), "judge pending (`mengine-bench judge`)"))
            continue
        entry = RankedBundle(result=result, summary_link=_link(bundle / SUMMARY_NAME, link_base))
        groups.setdefault(_group_key(result), []).append(entry)
    order = {suite: index for index, suite in enumerate(SUITES)}
    sections = [LEADERBOARD_HEADER]
    for key in sorted(groups, key=lambda key: (order.get(key[0], 99), key[1], key[2], key[3])):
        suite, version, label, profile = key
        title = f"judge {label}" if label else "no judge"
        rows = sorted(groups[key], key=lambda e: -float(e.result["totals"]["objective"]))  # type: ignore[index]
        sections.append(f"## {suite.upper()}, {title}, visual {profile} (scoring {version})\n\n" + _table(rows))
    if not groups:
        sections.append("No results yet.\n")
    if unranked:
        lines = [f"- `{name}`: {reason}" for name, reason in unranked]
        sections.append("## Not ranked\n\n" + "\n".join(lines) + "\n")
    ranked = sum(len(rows) for rows in groups.values())
    return Leaderboard(markdown="\n".join(sections), ranked=ranked, unranked=unranked)


def _table(rows: Iterable[RankedBundle]) -> str:
    lines = ["| # | agent | model | effort | OBJECTIVE | ACCURACY | solved | agent time (s) | SUBJECTIVE | "
             "COMPOSITE | date | bench | bundle |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for rank, entry in enumerate(rows, start=1):
        row = entry.result
        agent, totals = row["agent"], row["totals"]
        assert isinstance(agent, dict) and isinstance(totals, dict)
        lines.append(f"| {rank} | {agent['name']} {agent.get('version') or ''} | {agent['model']} | "
                     f"{_fmt(agent.get('effort'))} | {_fmt(totals['objective'])} | {_fmt(totals.get('accuracy'))} | "
                     f"{totals['solved']}/{totals['total']} | {_fmt(totals.get('total_agent_s'))} | "
                     f"{_fmt(totals.get('subjective'))} | {_fmt(totals.get('composite'))} | {row['date']} | "
                     f"{row['bench_version']} | [summary]({entry.summary_link}) |")
    return "\n".join(lines) + "\n"
