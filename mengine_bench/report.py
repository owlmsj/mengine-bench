"""result.json content, the Markdown summary, the docs/TASKS.md table and the README task summaries.

Results are public: they record environment facts (OS, CPU, GPU name) but
never local paths. Bundles (bundle.py) add redacted transcripts next to them.
"""

from __future__ import annotations

import platform
import shutil
import subprocess
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import TypedDict

import psutil

from mengine_bench import __version__
from mengine_bench.core import EvalTask
from mengine_bench.scoring import SuiteScore, TaskScore
from mengine_bench.visual import PROFILE_RENDERED, PROFILE_UNRENDERED

RESULT_SCHEMA = "mengine-bench/result@4"
TASKS_BEGIN = "<!-- tasks:begin (generated by `mengine-bench tasks-doc --write`) -->"
TASKS_END = "<!-- tasks:end -->"
SUMMARIES_BEGIN = "<!-- task-summaries:begin (generated by `mengine-bench tasks-doc --readme`) -->"
SUMMARIES_END = "<!-- task-summaries:end -->"


class TaskDetail(TypedDict):
    """Run facts per task that scoring does not carry."""

    steps: list[dict[str, object]]
    grading_s: float
    checks: list[dict[str, object]]
    check_score: float
    mandatory_ok: bool
    passed: bool
    flags: list[str]
    error: str | None
    judge_rationales: list[str]
    judge_errors: list[str]
    answers: list[str]
    # Vision checklist ballots, so a reviewer can redo the majority math.
    vision: dict[str, object] | None


@dataclass(frozen=True)
class RunMeta:
    date: str
    agent: str
    model: str
    effort: str | None
    agent_version: str | None
    judge_label: str | None
    judge_votes: int
    run_id: str
    started_at: str
    finished_at: str
    submitter: str | None = None
    judge_model: str | None = None
    judge_effort: str | None = None


def _gpu_name() -> str | None:
    smi = shutil.which("nvidia-smi")
    if smi is None:
        return None
    try:
        proc = subprocess.run([smi, "--query-gpu=name", "--format=csv,noheader"], capture_output=True, text=True,
                              timeout=10, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    names = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
    return ", ".join(names) if proc.returncode == 0 and names else None


def collect_environment() -> dict[str, object]:
    return {
        "os": f"{platform.system()} {platform.release()}",
        "cpu": platform.processor() or platform.machine(),
        "cpu_count": psutil.cpu_count(logical=True),
        "ram_gb": round(psutil.virtual_memory().total / 2**30, 1),
        "gpu": _gpu_name(),
        "python": platform.python_version(),
    }


def _task_entry(score: TaskScore, detail: TaskDetail, votes: Sequence[int]) -> dict[str, object]:
    return {
        "id": score.task_id, "category": score.category,
        "status": score.status, "error": detail["error"], "flags": detail["flags"],
        "steps": detail["steps"], "agent_s": None if score.agent_s is None else round(score.agent_s, 2),
        "grading_s": round(detail["grading_s"], 2), "checks": detail["checks"],
        "check_score": detail["check_score"], "mandatory_ok": detail["mandatory_ok"], "passed": detail["passed"],
        "c": score.correctness, "o": round(score.objective, 2),
        "judge_votes": list(votes), "subjective": score.subjective,
        "judge_rationales": detail["judge_rationales"], "judge_errors": detail["judge_errors"],
        "answers": detail["answers"], "vision": detail["vision"],
    }


def _judge_block(meta: RunMeta) -> dict[str, object] | None:
    if meta.judge_label is None:
        return None
    return {"label": meta.judge_label, "model": meta.judge_model, "effort": meta.judge_effort,
            "votes": meta.judge_votes}


def visual_grading_profile(task_flags: Iterable[Sequence[str]]) -> str:
    """Run-level profile: "unrendered" as soon as one visual task was graded
    without a browser screenshot and vision judge (visual.py, review R10)."""
    unrendered = any(PROFILE_UNRENDERED in flags for flags in task_flags)
    return PROFILE_UNRENDERED if unrendered else PROFILE_RENDERED


def totals_block(suite: SuiteScore) -> dict[str, object]:
    return {
        "objective": suite.objective, "accuracy": suite.accuracy, "solved": suite.solved, "total": suite.total,
        "total_agent_s": suite.total_agent_s, "subjective": suite.subjective, "composite": suite.composite,
        "by_category": {name: vars(cat) for name, cat in suite.by_category.items()},
    }


def build_results(meta: RunMeta, suite: SuiteScore, details: Mapping[str, TaskDetail],
                  votes: Mapping[str, Sequence[int]], environment: Mapping[str, object],
                  commit: Mapping[str, object]) -> dict[str, object]:
    judge = _judge_block(meta)
    grading = {"visual": visual_grading_profile(detail["flags"] for detail in details.values())}
    run_environment = {
        **environment, "agent_cli": {"name": meta.agent, "version": meta.agent_version},
        "model": meta.model, "effort": meta.effort,
        "judge": None if judge is None else {key: judge[key] for key in ("model", "effort", "votes")},
    }
    return {
        "schema": RESULT_SCHEMA, "bench_version": __version__, "bench_commit": dict(commit),
        "scoring_version": suite.scoring_version, "run_id": meta.run_id, "submitter": meta.submitter,
        "date": meta.date, "started_at": meta.started_at, "finished_at": meta.finished_at,
        "agent": {"name": meta.agent, "model": meta.model, "effort": meta.effort, "version": meta.agent_version},
        "judge": judge,
        "grading": grading,
        "environment": run_environment,
        "totals": totals_block(suite),
        "tasks":[_task_entry(task, details[task.task_id], votes.get(task.task_id, ())) for task in suite.tasks],
    }


def _fmt(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.1f}"
    return str(value)


def _commit_text(commit: object) -> str:
    if not isinstance(commit, dict) or not commit.get("sha"):
        return "unknown commit"
    return f"{str(commit['sha'])[:12]}{' (dirty tree)' if commit.get('dirty') else ''}"


def _visual_profile_text(results: Mapping[str, object]) -> str:
    grading = results.get("grading")
    return str(grading.get("visual")) if isinstance(grading, dict) else "not recorded"


def _preflight_text(results: Mapping[str, object]) -> str:
    found = results.get("preflight")
    if found is None:
        return "not recorded (bench before 0.2.0)"
    assert isinstance(found, list)
    return "clean" if not found else "NOT CLEAN, not ranked: " + "; ".join(str(item) for item in found)


def render_summary(results: Mapping[str, object]) -> str:
    agent = results["agent"]
    totals = results["totals"]
    judge = results["judge"]
    assert isinstance(agent, dict) and isinstance(totals, dict)
    judge_text = judge["label"] if isinstance(judge, dict) else "none"
    if isinstance(judge, dict) and judge.get("deferred"):
        judge_text += " (judged after the run with `mengine-bench judge`)"
    if judge is None and results.get("judge_pending"):
        judge_text = "pending (the maintainer runs `mengine-bench judge` on review)"
    lines = [
        f"# mengine-bench: {agent['name']} / {agent['model']}",
        "",
        f"- Date: {results['date']}; scoring version {results['scoring_version']}; "
        f"effort {_fmt(agent['effort'])}; agent version {_fmt(agent['version'])}; judge {judge_text}; "
        f"visual grading: {_visual_profile_text(results)}",
        f"- OBJECTIVE: **{_fmt(totals['objective'])}**; accuracy {_fmt(totals['accuracy'])}; "
        f"solved {totals['solved']}/{totals['total']}; agent time {_fmt(totals['total_agent_s'])} s",
        f"- SUBJECTIVE: {_fmt(totals['subjective'])}; COMPOSITE: {_fmt(totals['composite'])}",
        f"- Preflight: {_preflight_text(results)}",
        f"- Bench {results['bench_version']} at {_commit_text(results.get('bench_commit'))}; "
        f"submitter {_fmt(results.get('submitter'))}; started {_fmt(results.get('started_at'))}",
        "",
        "| task | status | time (s) | checks | c | judge |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    tasks = results["tasks"]
    assert isinstance(tasks, list)
    for task in tasks:
        checks = task["checks"]
        passed = sum(1 for check in checks if check["ok"])
        flags = f" ({', '.join(task['flags'])})" if task["flags"] else ""
        lines.append(f"| {task['id']} | {task['status']}{flags} | {_fmt(task['agent_s'])} | "
                     f"{passed}/{len(checks)} | {task['c']:.2f} | {_fmt(task['subjective'])} |")
    return "\n".join(lines) + "\n"


def render_tasks_table(tasks: Iterable[EvalTask]) -> str:
    """Task table (#23): id, category and the one-sentence TL;DR."""
    lines = ["| id | category | TL;DR |", "| --- | --- | --- |"]
    for task in tasks:
        summary = task.summary.replace("|", "/")
        lines.append(f"| `{task.id}` | {task.category} | {summary} |")
    return "\n".join(lines) + "\n"


def render_task_summaries(tasks: Iterable[EvalTask]) -> str:
    """README task table: the same table as render_tasks_table."""
    return render_tasks_table(tasks)


def replace_tasks_table(doc: str, table: str, begin: str = TASKS_BEGIN, end: str = TASKS_END) -> str:
    start, stop = doc.find(begin), doc.find(end)
    if start < 0 or stop < start:
        raise ValueError(f"received a document without {begin!r} ... {end!r}; expected both markers in order")
    return doc[:start + len(begin)] + "\n" + table + doc[stop:]
