"""result.json content, the Markdown summary and the generated task tables.

Results are public: they record environment facts (OS, CPU, GPU name) but
never local paths. Bundles (bundle.py) add redacted transcripts next to them.
"""

from __future__ import annotations

import platform
import shutil
import subprocess
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import TypedDict

import psutil

from mengine_bench import __version__
from mengine_bench.core import EvalTask
from mengine_bench.runner.agents import Usage
from mengine_bench.scoring import Price, RunScore, TaskScore, TokenTotals

RESULT_SCHEMA = "mengine-bench/result@5"
TASKS_BEGIN = "<!-- tasks:begin (generated by `mengine-bench tasks-doc --write`) -->"
TASKS_END = "<!-- tasks:end -->"
SUMMARIES_BEGIN = "<!-- task-summaries:begin (generated by `mengine-bench tasks-doc --readme`) -->"
SUMMARIES_END = "<!-- task-summaries:end -->"
JUDGE_PENDING = "pending (the maintainer runs `mengine-bench judge` on review)"


class TaskDetail(TypedDict):
    """Run facts per task that scoring does not carry."""

    steps: list[dict[str, object]]
    grading_s: float
    checks: list[dict[str, object]]
    flags: list[str]
    error: str | None
    answers: list[str]
    usage: dict[str, object] | None


@dataclass(frozen=True)
class RunMeta:
    date: str
    agent: str
    model: str
    effort: str | None
    agent_version: str | None
    run_id: str
    started_at: str
    finished_at: str
    submitter: str | None = None
    price: Price | None = None
    config: Mapping[str, object] = field(default_factory=dict)


def usage_record(usage: Usage | None) -> dict[str, object] | None:
    """Token counts and harness USD of one step or task; None when unmeasured."""
    if usage is None:
        return None
    return {"input_tokens": usage.input_tokens, "cached_input_tokens": usage.cached_input_tokens,
            "output_tokens": usage.output_tokens, "reasoning_tokens": usage.reasoning_tokens,
            "cost_usd": usage.cost_usd, "cost_source": usage.cost_source}


def _gpu_name() -> str | None:
    smi = shutil.which("nvidia-smi")
    if smi is None:
        return None
    try:
        proc = subprocess.run([smi, "--query-gpu=name", "--format=csv,noheader"], capture_output=True, text=True,
                              timeout=10, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    names = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
    return ", ".join(names) if proc.returncode == 0 and names else None


def collect_environment() -> dict[str, object]:
    return {
        "os": f"{platform.system()} {platform.release()}",
        "cpu": platform.processor() or platform.machine(),
        "cpu_count": psutil.cpu_count(logical=True),
        "ram_gb": round(psutil.virtual_memory().total / 2**30, 1),
        "gpu": _gpu_name(),
        "python": platform.python_version(),
    }


def _tokens_record(tokens: TokenTotals) -> dict[str, int]:
    return {"input": tokens.input, "cached_input": tokens.cached_input, "output": tokens.output,
            "reasoning": tokens.reasoning}


def _task_entry(score: TaskScore, detail: TaskDetail) -> dict[str, object]:
    return {
        "id": score.task_id, "status": score.status, "error": detail["error"], "flags": detail["flags"],
        "c": score.correctness, "solved": score.solved, "checks": detail["checks"],
        # Set by `mengine-bench judge` on review (#23): one rubric vote per task.
        "judge": score.judge, "judge_rationale": None, "judge_errors": [],
        "agent_s": None if score.agent_s is None else round(score.agent_s, 2),
        "grading_s": round(detail["grading_s"], 2), "cost_usd": score.cost_usd,
        "tokens": _tokens_record(score.tokens), "usage": detail["usage"], "steps": detail["steps"],
        "answers": detail["answers"],
    }


def totals_block(run: RunScore) -> dict[str, object]:
    return {
        "score": run.score, "correct": run.correct, "solved": run.solved, "total": run.total, "judge": run.judge,
        "time_s": run.time_s, "cost_usd": run.cost.usd, "cost_basis": run.cost.basis,
        "cost_lower_bound": run.cost.lower_bound, "tokens": _tokens_record(run.tokens),
    }


def build_results(meta: RunMeta, run: RunScore, details: Mapping[str, TaskDetail],
                  environment: Mapping[str, object], commit: Mapping[str, object]) -> dict[str, object]:
    price = None if meta.price is None else {"input": meta.price.input, "cached": meta.price.cached,
                                             "output": meta.price.output}
    run_environment = {
        **environment, "agent_cli": {"name": meta.agent, "version": meta.agent_version},
        "model": meta.model, "effort": meta.effort,
    }
    return {
        "schema": RESULT_SCHEMA, "bench_version": __version__, "bench_commit": dict(commit),
        "run_id": meta.run_id, "submitter": meta.submitter,
        "date": meta.date, "started_at": meta.started_at, "finished_at": meta.finished_at,
        "agent": {"name": meta.agent, "model": meta.model, "effort": meta.effort, "version": meta.agent_version},
        "config": dict(meta.config), "price_per_mtok": price,
        "judge": None,
        "environment": run_environment,
        "totals": totals_block(run),
        "tasks": [_task_entry(task, details[task.task_id]) for task in run.tasks],
    }


def _fmt(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.1f}"
    return str(value)


def time_text(seconds: object) -> str:
    if not isinstance(seconds, (int, float)):
        return "-"
    minutes, rest = divmod(round(float(seconds)), 60)
    return f"{minutes} min {rest:02d} s" if minutes else f"{float(seconds):.1f} s"


def cost_text(totals: Mapping[str, object]) -> str:
    """'$1.23 (harness)', '>= $1.23 (price)' when a step went unmeasured, or 'n/a'."""
    usd = totals.get("cost_usd")
    if not isinstance(usd, (int, float)):
        return "n/a"
    bound = ">= " if totals.get("cost_lower_bound") else ""
    return f"{bound}${usd:.2f} ({totals.get('cost_basis')})"


def tokens_text(tokens: object) -> str:
    if not isinstance(tokens, dict):
        return "-"
    total = int(tokens.get("input", 0)) + int(tokens.get("output", 0))
    return f"{total / 1e6:.2f}M"


def _commit_text(commit: object) -> str:
    if not isinstance(commit, dict) or not commit.get("sha"):
        return "unknown commit"
    return f"{str(commit['sha'])[:12]}{' (dirty tree)' if commit.get('dirty') else ''}"


def _preflight_text(results: Mapping[str, object]) -> str:
    found = results.get("preflight")
    if found is None:
        return "not recorded"
    assert isinstance(found, list)
    return "clean" if not found else "NOT CLEAN, not ranked: " + "; ".join(str(item) for item in found)


def judge_text(judge: object) -> str:
    if not isinstance(judge, dict):
        return JUDGE_PENDING
    return f"{judge.get('model')}@{judge.get('effort') or 'default'}, rubric {judge.get('rubric')}"


def render_summary(results: Mapping[str, object]) -> str:
    agent = results["agent"]
    totals = results["totals"]
    assert isinstance(agent, dict) and isinstance(totals, dict)
    lines = [
        f"# mengine-bench {results['bench_version']}: {agent['name']} {agent.get('version') or ''} / "
        f"{agent['model']} ({agent.get('effort') or 'default effort'})",
        "",
        "| Score | Correct % | Solved | Judge | Time | Cost | Tokens |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        f"| **{_fmt(totals['score'])}** | {_fmt(totals['correct'])} | {totals['solved']}/{totals['total']} | "
        f"{_fmt(totals['judge'])} | {time_text(totals['time_s'])} | {cost_text(totals)} | "
        f"{tokens_text(totals.get('tokens'))} |",
        "",
        f"- Judge: {judge_text(results.get('judge'))}",
        f"- Preflight: {_preflight_text(results)}",
        f"- Run: {results['date']}, started {_fmt(results.get('started_at'))}; bench at "
        f"{_commit_text(results.get('bench_commit'))}; submitter {_fmt(results.get('submitter'))}",
        "",
        "| task | status | correct | checks | judge | time | cost (USD) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    tasks = results["tasks"]
    assert isinstance(tasks, list)
    for task in tasks:
        checks = task["checks"]
        passed = sum(1 for check in checks if check["ok"])
        flags = f" ({', '.join(task['flags'])})" if task["flags"] else ""
        cost = task.get("cost_usd")
        lines.append(f"| {task['id']} | {task['status']}{flags} | {100 * task['c']:.0f}% | {passed}/{len(checks)} | "
                     f"{_fmt(task.get('judge'))} | {time_text(task['agent_s'])} | "
                     f"{'-' if cost is None else f'{cost:.4f}'} |")
    return "\n".join(lines) + "\n"


def render_tasks_table(tasks: Iterable[EvalTask]) -> str:
    """Task table (#23): id, category and the one-sentence TL;DR."""
    lines = ["| id | category | TL;DR |", "| --- | --- | --- |"]
    for task in tasks:
        summary = task.summary.replace("|", "/")
        lines.append(f"| `{task.id}` | {task.category} | {summary} |")
    return "\n".join(lines) + "\n"


def render_task_summaries(tasks: Iterable[EvalTask]) -> str:
    """README task table: the same table as render_tasks_table."""
    return render_tasks_table(tasks)


def replace_tasks_table(doc: str, table: str, begin: str = TASKS_BEGIN, end: str = TASKS_END) -> str:
    start, stop = doc.find(begin), doc.find(end)
    if start < 0 or stop < start:
        raise ValueError(f"received a document without {begin!r} ... {end!r}; expected both markers in order")
    return doc[:start + len(begin)] + "\n" + table + doc[stop:]
